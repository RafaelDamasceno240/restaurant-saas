import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsIn, IsInt, IsOptional, IsString, IsUUID, Matches, Max, MaxLength, Min, MinLength } from 'class-validator';
import { ON_ACCOUNT_DISABLED_MESSAGE, SALE_PAYMENT_METHODS } from '../../../common/util/payment-methods';
import { PaymentMethod } from '@prisma/client';

// No amount/price/total field exists here: the sale total is always the sum
// of the TabItem snapshots, computed server-side.
export class CheckoutTabDto {
  // Money received now. Fiado (ON_ACCOUNT) is no longer sold (remocao-fiado).
  @ApiProperty({ enum: SALE_PAYMENT_METHODS })
  @IsIn(SALE_PAYMENT_METHODS, { message: ON_ACCOUNT_DISABLED_MESSAGE })
  paymentMethod!: PaymentMethod;

  // Generated by the client once per checkout attempt (e.g. a UUID) and
  // re-sent on retries. Unique per tenant in the DB (orders_tenantId_idempotencyKey_key).
  @ApiProperty({ example: '6f1c2c1e-6d0e-4f4a-9a57-2f3a0a1b9c11' })
  @IsString()
  @MinLength(8)
  @MaxLength(100)
  @Matches(/^[A-Za-z0-9_-]+$/, { message: 'idempotencyKey deve conter apenas letras, números, "-" ou "_".' })
  idempotencyKey!: string;

  // Fase 11: optional customer of the registry the sale belongs to. Validated server-side
  // against the caller's tenant (and the customers.read permission); only the id travels.
  @ApiPropertyOptional({ description: 'Cliente cadastrado a vincular à venda' })
  @IsOptional()
  @IsUUID()
  customerId?: string;

  // Fase 11 (fatia 5): cents of that customer's cashback balance to spend on this sale. Needs a
  // customerId and the cashback.use permission; validated server-side against the real balance.
  @ApiPropertyOptional({ description: 'Centavos de cashback do cliente a usar nesta venda' })
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(2_147_483_647)
  cashbackToUseCents?: number;
}
